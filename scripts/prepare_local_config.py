"""Deep-merge the tracked config with an untracked local override.

Usage:
    python scripts/prepare_local_config.py <base.yaml> <override.yaml> <output.yaml>

The output is written next to the backend config and loaded via
``config=config.effective.yaml``. The local override is intentionally small
(e.g. only redis_url / celery_redis_url), so the tracked config stays clean.
"""

from __future__ import annotations

import sys
from pathlib import Path

import yaml


def deep_merge(base: dict, override: dict) -> dict:
    result = dict(base)
    for key, value in override.items():
        if isinstance(result.get(key), dict) and isinstance(value, dict):
            result[key] = deep_merge(result[key], value)
        else:
            result[key] = value
    return result


def main() -> int:
    if len(sys.argv) != 4:
        print("usage: prepare_local_config.py <base.yaml> <override.yaml> <output.yaml>", file=sys.stderr)
        return 2

    base_path = Path(sys.argv[1])
    override_path = Path(sys.argv[2])
    output_path = Path(sys.argv[3])

    try:
        base = yaml.safe_load(base_path.read_text(encoding="utf-8")) or {}
        override = yaml.safe_load(override_path.read_text(encoding="utf-8")) or {}
    except (OSError, yaml.YAMLError) as exc:
        print(f"failed to read config: {exc}", file=sys.stderr)
        return 1

    if not isinstance(base, dict) or not isinstance(override, dict):
        print("config files must contain a YAML mapping at the root", file=sys.stderr)
        return 1

    merged = deep_merge(base, override)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with output_path.open("w", encoding="utf-8", newline="\n") as f:
        f.write("# AUTO-GENERATED by scripts/prepare_local_config.py; do not edit.\n")
        yaml.safe_dump(
            merged,
            f,
            allow_unicode=True,
            sort_keys=False,
            default_flow_style=False,
        )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
